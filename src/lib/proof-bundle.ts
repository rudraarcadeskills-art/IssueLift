import { ContributionContract } from './types';

export function generateProofBundleMarkdown(contract: ContributionContract): string {
  const meta = contract.issue_metadata;
  const gate = contract.readiness_gate;
  const audit = contract.claim_gate_audit;

  const criteriaRows = contract.criteria
    .map((c) => {
      const typeBadge = c.criterion_type === 'EXPLICIT' ? '`[EXPLICIT]`' : '`[AI-PROPOSED]`';
      const quoteStr = c.exact_quote ? `\n> *Quote:* "${c.exact_quote.replace(/"/g, '\\"')}"` : '';
      const clarifBadge = c.needs_maintainer_clarification ? ' ⚠️ *Needs Clarification*' : '';
      return `### ${c.id}: ${c.description} ${typeBadge} (${c.status})${clarifBadge}${quoteStr}
- **Status Rationale:** ${c.status_rationale}
- **Candidate Files:** ${
        c.candidate_implementation_files.length > 0
          ? c.candidate_implementation_files
              .map((f) => `\`${f.path}\` (${f.verified_exists ? 'Verified Exists' : 'Unverified'})`)
              .join(', ')
          : '_None identified in bounded context_'
      }
- **Test Evidence:** ${c.test_evidence.status}
  - _Test candidates:_ ${
    c.test_evidence.candidate_test_files.length > 0
      ? c.test_evidence.candidate_test_files.map((t) => `\`${t.path}\``).join(', ')
      : '_No test evidence found in scanned files_'
  }
  - _Rationale:_ ${c.test_evidence.rationale}
  - _Manual Validation Scenario:_ ${c.test_evidence.proposed_manual_validation || 'Local reproduction before/after patch.'}
`;
    })
    .join('\n');

  return `# ISSUELIFT CONTRIBUTION PROOF BUNDLE
*Generated by IssueLift v1.3 • Pre-contribution Contract & TraceMap Engine*
*Checked at:* \`${contract.scan_boundaries.checked_at}\`

---

## 1. Issue Metadata & Readiness Gate
- **Target Issue:** [${meta.owner}/${meta.repo} #${meta.number}: ${meta.title}](${meta.url})
- **Status:** \`${meta.state.toUpperCase()}\`
- **Assignees:** ${meta.assignees.length > 0 ? meta.assignees.map((a) => `@${a.login}`).join(', ') : '_Unassigned_'}
- **Labels:** ${meta.labels.length > 0 ? meta.labels.map((l) => `\`${l.name}\``).join(' ') : '_None_'}
- **Default Branch:** \`${meta.default_branch}\`
- **Readiness Gate Verdict:** **\`${gate.verdict}\`**
${gate.reasons.map((r) => `  - ${r}`).join('\n')}

---

## 2. Executive Contract Summary
- **Summary:** ${contract.issue_summary}
- **Expected Outcome:** ${contract.expected_outcome}

---

## 3. Acceptance-to-Test TraceMap (Contribution Contract)
${criteriaRows}

---

## 4. Setup Truth & Commands
- **Install Command:** ${
    contract.setup_truth.install_command
      ? `\`${contract.setup_truth.install_command.command}\` (${contract.setup_truth.install_command.label})`
      : '_Not documented in scanned files_'
  }
- **Test Command:** ${
    contract.setup_truth.test_command
      ? `\`${contract.setup_truth.test_command.command}\` (${contract.setup_truth.test_command.label})`
      : '_Not documented in scanned files_'
  }
- **Run Command:** ${
    contract.setup_truth.run_command
      ? `\`${contract.setup_truth.run_command.command}\` (${contract.setup_truth.run_command.label})`
      : '_Not documented in scanned files_'
  }
- **Documentation Found:** README: ${contract.setup_truth.has_readme ? 'Yes' : 'No'} | CONTRIBUTING: ${
    contract.setup_truth.has_contributing ? 'Yes' : 'No'
  }
- **Setup Notes:** ${contract.setup_truth.notes}

---

## 5. Copy-Ready Maintainer Handoff
> **Note for Contributors:** Review and edit this comment before copying to GitHub. IssueLift never posts automatically.

\`\`\`markdown
${contract.maintainer_handoff.clarification_question}

${contract.maintainer_handoff.proposed_criteria_addition ? `Proposed Acceptance Criteria:\n${contract.maintainer_handoff.proposed_criteria_addition}\n` : ''}
${contract.maintainer_handoff.suggested_validation_scenario ? `Validation Plan:\n${contract.maintainer_handoff.suggested_validation_scenario}\n` : ''}
*Context compiled with [IssueLift](https://github.com/issuelift/issuelift) (ProofBench verified).*
\`\`\`

---

## 6. First-Hour Route
${contract.first_hour_route.map((step, idx) => `${idx + 1}. ${step}`).join('\n')}

---

## 7. Pre-PR Checklist
${contract.pr_checklist.map((item) => `- [ ] ${item}`).join('\n')}

---

## 8. Deterministic Claim Gate Audit
- **Files in Repository Tree:** ${contract.scan_boundaries.total_files_in_tree}
- **Scanned Evidence Sources:** ${contract.scan_boundaries.scanned_files_count}
- **Tree Truncation Status:** ${contract.scan_boundaries.is_tree_truncated ? 'TRUNCATED (bounded context)' : 'Complete'}
- **Rejected Hallucinated Paths:** ${audit.rejected_paths_count}
- **Rejected Fabricated Source IDs:** ${audit.rejected_source_ids_count}
- **AI Engine:** ${contract.ai_configured ? `Google Gemma 4 (${contract.model_id})` : 'Baseline Compiler (GEMMA_API_KEY pending)'}
${audit.warnings.length > 0 ? `\n### Audit Warnings:\n${audit.warnings.map((w) => `- ${w}`).join('\n')}` : ''}

---
*Notice: ProofBench fixtures ensure validation invariants. IssueLift never executes untrusted repository code.*
`;
}

export function generateProofBundleJson(contract: ContributionContract): string {
  return JSON.stringify(contract, null, 2);
}
